/**
 * Mechanical fold digest: doctrine-shaped, zero-LLM, bounded.
 */
import assert from 'node:assert/strict'
import { test } from 'node:test'

import { estimateTokens } from '../lib/fold.js'
import { buildMechanicalDigest, MECHANICAL_DIGEST_CAP, messageText } from '../lib/fold-digest.js'

const fixture = {
  tools: [{ name: 'bash' }],
  messages: [
    { role: 'system', content: 'You are a coding assistant. SYSTEM HEAD: must never appear in the digest.' },
    { role: 'user', content: 'fix the sqlite migration crash and push to main' },
    {
      role: 'tool',
      content: [
        { type: 'text', text: 'ERROR: sqlite lock timeout in ci\n  at runMigration (/srv/app/migrate.ts:142:11)\nstep 42 ok' },
      ],
    },
    { role: 'assistant', content: 'Migration commit 7f3a1c2 pushed to main; flake was a lock timeout.' },
    { role: 'user', content: 'now add the backfill script, port 54330' },
  ],
}

test('the digest is task-relative and keeps the doctrine priority order', () => {
  const { digest } = buildMechanicalDigest(fixture)
  assert.ok(digest.startsWith('TASK AS OF THIS BLOCK'))
  assert.ok(digest.includes('fix the sqlite migration crash and push to main'), 'the goal is kept verbatim')
  assert.ok(digest.includes('7f3a1c2'), 'load-bearing values stay exact')
  assert.ok(digest.includes('54330'), 'exact ports stay exact')
  assert.ok(!digest.includes('SYSTEM HEAD'), 'the system head never enters the digest')
  assert.ok(digest.includes('generated by mulqi-context-compression'), 'provenance line is present')
})

test('error lines are surfaced verbatim from tool output', () => {
  const { digest } = buildMechanicalDigest(fixture)
  assert.ok(digest.includes('sqlite lock timeout'), 'the exact error string survives')
  assert.ok(digest.includes('/srv/app/migrate.ts'), 'file paths survive')
})

test('the digest fits the tier-1 block cap by default', () => {
  const big = {
    messages: [
      { role: 'user', content: 'goal ' + 'x'.repeat(400) },
      ...Array.from({ length: 60 }, (_, i) => ({
        role: 'assistant',
        content: `iteration ${i}: ${'payload '.repeat(40)}`,
      })),
    ],
  }
  const { digest, tokens } = buildMechanicalDigest(big)
  assert.ok(estimateTokens(digest) <= MECHANICAL_DIGEST_CAP, `digest is within the default cap (${tokens} tokens)`)
})

test('an explicit cap dominates and trims least-important sections first', () => {
  const { digest } = buildMechanicalDigest(fixture, { capTokens: 120 })
  assert.ok(estimateTokens(digest) <= 120)
  assert.ok(digest.includes('## Goal'), 'the goal section survives a tight budget')
  assert.ok(digest.includes('## Final state'), 'the final state section survives a tight budget')
})

test('the digest is deterministic for identical input', () => {
  assert.equal(buildMechanicalDigest(fixture).digest, buildMechanicalDigest(fixture).digest)
})

test('an empty region degrades to a skeleton, never a crash', () => {
  const { digest } = buildMechanicalDigest({ messages: [] })
  assert.ok(digest.startsWith('TASK AS OF THIS BLOCK'))
  assert.ok(digest.includes('(none)'))
})

test('messageText normalizes strings, blocks, and tool calls', () => {
  assert.equal(messageText('plain'), 'plain')
  assert.equal(
    messageText([{ type: 'text', text: 'a' }, { type: 'toolCall', name: 'bash' }, { type: 'image' }]),
    'a\n[tool-call bash]\n[image]',
  )
  assert.equal(messageText(undefined), '')
})
